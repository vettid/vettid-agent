// hasSmallOrder reports whether the supplied X25519 public key matches
// one of the small-order generators. Constant-time across entries.
func hasSmallOrder(point []byte) bool {
	if len(point) != 32 {
		return false
	}
	var hit int
	for i := range smallOrderPoints {
		hit |= subtle.ConstantTimeCompare(point, smallOrderPoints[i][:])
	}
	return hit != 0
}

// safeX25519 wraps curve25519.X25519 with the small-order pre-check.
// Use this anywhere the `point` (public key) crosses a trust boundary —
// every ECIES decrypt site and every wire-side ECDH key-exchange site.
func safeX25519(scalar, point []byte) ([]byte, error) {
	if hasSmallOrder(point) {
		return nil, fmt.Errorf("peer public key has small order")
	}
	return curve25519.X25519(scalar, point)
}
